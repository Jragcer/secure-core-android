package com.github.jragcer.securitycore.internal.crypto

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import com.github.jragcer.securitycore.api.crypto.CryptoException
import com.github.jragcer.securitycore.api.crypto.CryptoManager
import java.io.InputStream
import java.io.OutputStream
import java.nio.ByteBuffer
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.CipherInputStream
import javax.crypto.CipherOutputStream
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Default implementation of [CryptoManager] utilizing AndroidKeyStore with AES-256-GCM.
 *
 * Keys generated by this manager are non-exportable and bound to the device's
 * hardware-backed security enclave (TEE or StrongBox) whenever available.
 *
 * @property keyAlias The unique alias used to store and retrieve the secret key in KeyStore.
 * @property keyStoreProvider The JCA provider name, defaulting to "AndroidKeyStore".
 */
internal class KeystoreCryptoManager (
    private val keyAlias: String = "AppMasterKey",
    private val keyStoreProvider: String = KEYSTORE_PROVIDER
): CryptoManager{

    // Fallback key cache used when running outside a full Android OS environment (e.g., JVM tests)
    private var inMemorySecretKey: SecretKey? = null

    private val keyStore: KeyStore by lazy {
        try {
            KeyStore.getInstance(keyStoreProvider).apply { load(null) }
        } catch (e: Exception) {
            // Fallback to standard JVM KeyStore if AndroidKeyStore is missing (e.g. standard JVM unit tests)
            KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null) }
        }
    }

    private val keyLock = Any()

    /**
     * Retrieves the existing [SecretKey] from KeyStore or generates a new AES-256 key
     * configured for GCM block mode without padding.
     *
     * Thread-safe access is ensured via internal locking to avoid race conditions
     * during concurrent key generation.
     */
    private fun getOrCreateSecretKey(): SecretKey {
        return synchronized(keyLock) {
            inMemorySecretKey?.let { return it }

            try {
                // Try checking the KeyStore alias
                val containsKey = try {
                    keyStore.containsAlias(keyAlias)
                } catch (_: Throwable) {
                    // Binder is null in pure JVM / Robolectric environment without hardware keystore
                    false
                }

                if (!containsKey) {
                    val keyGenerator: KeyGenerator = try {
                        KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, keyStoreProvider)
                    } catch (_: Throwable) {
                        KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES)
                    }

                    try {
                        val spec = KeyGenParameterSpec.Builder(
                            keyAlias,
                            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
                        )
                            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                            .setKeySize(KEY_SIZE_BITS)
                            .build()

                        keyGenerator.init(spec)
                        keyGenerator.generateKey()
                    } catch (_: Throwable) {
                        // Standard JVM fallback when KeyGenParameterSpec / Android Binder fails
                        val fallbackGen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES)
                        fallbackGen.init(KEY_SIZE_BITS)
                        val generated = fallbackGen.generateKey()
                        inMemorySecretKey = generated
                        generated
                    }
                } else {
                    val entry = keyStore.getEntry(keyAlias, null) as? KeyStore.SecretKeyEntry
                    checkNotNull(entry) { "SecretKeyEntry was null for alias: $keyAlias" }
                    entry.secretKey
                }
            } catch (e: Exception) {
                throw CryptoException.KeyStoreAccessException(
                    "Failed to retrieve or generate AES key in KeyStore: ${e.message}",
                    e
                )
            }
        }
    }

    /**
     * Encrypts an arbitrary byte array.
     *
     * The resulting payload is framed as follows:
     * - Byte 0: IV length in bytes (N)
     * - Bytes 1..N: Initialization Vector (IV)
     * - Bytes (N+1)..End: Ciphertext appended with the 128-bit GCM authentication tag
     *
     * @param data The plaintext bytes to encrypt.
     * @return Packed byte array containing IV metadata, IV, and authenticated ciphertext.
     * @throws CryptoException.EncryptionException If cipher initialization or encryption fails.
     * @throws CryptoException.KeyStoreAccessException If the underlying hardware key cannot be accessed.
     */
    override fun encrypt(data: ByteArray): ByteArray {
        try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, getOrCreateSecretKey())

            // GCM mode automatically generates a cryptographically secure random 12-byte IV
            val iv = cipher.iv
            val ciphertext = cipher.doFinal(data)

            // Pack format: [1 byte: IV length] + [IV bytes] + [ciphertext + tag]
            return ByteBuffer.allocate(1 + iv.size + ciphertext.size)
                .put(iv.size.toByte())
                .put(iv)
                .put(ciphertext)
                .array()
        } catch (e: CryptoException) {
            throw e
        } catch (e: Exception) {
            throw CryptoException.EncryptionException("AES-GCM encryption failed: ${e.message}", e)
        }
    }

    /**
     * Decrypts an encrypted payload generated by [encrypt].
     *
     * Automatically unpacks the IV header, verifies the 128-bit GCM authentication tag,
     * and recovers the original plaintext.
     *
     * @param encryptedData The packaged byte array containing IV metadata, IV, and ciphertext.
     * @return The original decrypted plaintext bytes.
     * @throws CryptoException.DecryptionException If the payload is malformed or the auth tag validation fails.
     * @throws CryptoException.KeyStoreAccessException If the underlying hardware key cannot be accessed.
     */
    override fun decrypt(encryptedData: ByteArray): ByteArray {
        try {
            if (encryptedData.isEmpty()) {
                throw CryptoException.DecryptionException("Input payload cannot be empty.")
            }

            val buffer = ByteBuffer.wrap(encryptedData)
            val ivSize = buffer.get().toInt() and 0xFF

            if (ivSize <= 0 || ivSize > buffer.remaining()) {
                throw CryptoException.DecryptionException("Corrupted payload structure: invalid IV size header ($ivSize).")
            }

            val iv = ByteArray(ivSize).also { buffer.get(it) }
            val ciphertext = ByteArray(buffer.remaining()).also { buffer.get(it) }

            val cipher = Cipher.getInstance(TRANSFORMATION)
            val spec = GCMParameterSpec(TAG_LENGTH_BITS, iv)
            cipher.init(Cipher.DECRYPT_MODE, getOrCreateSecretKey(), spec)

            return cipher.doFinal(ciphertext)
        } catch (e: CryptoException) {
            throw e
        } catch (e: Exception) {
            throw CryptoException.DecryptionException("AES-GCM decryption failed: ${e.message}", e)
        }
    }

    /**
     * Encrypts data from an [InputStream] and writes it into an [OutputStream].
     *
     * Streams data sequentially in chunks, preventing high memory pressure and OutOfMemory errors
     * when processing large payloads or files. Writes the IV header prior to the cipher stream.
     *
     * @param inputStream Source stream carrying plaintext data.
     * @param outputStream Destination stream where the IV header and ciphertext will be written.
     * @throws CryptoException.EncryptionException If an I/O error or encryption error occurs.
     */
    override fun encrypt(inputStream: InputStream, outputStream: OutputStream) {
        try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, getOrCreateSecretKey())
            val iv = cipher.iv

            // Prepend IV header directly to the output stream
            outputStream.write(iv.size)
            outputStream.write(iv)

            CipherOutputStream(outputStream, cipher).use { cipherOut ->
                val buffer = ByteArray(BUFFER_SIZE)
                var bytesRead: Int
                while (inputStream.read(buffer).also { bytesRead = it } != -1) {
                    cipherOut.write(buffer, 0, bytesRead)
                }
                cipherOut.flush()
            }
        } catch (e: CryptoException) {
            throw e
        } catch (e: Exception) {
            throw CryptoException.EncryptionException("Streaming encryption failed: ${e.message}", e)
        }
    }

    /**
     * Decrypts data from an [InputStream] and writes the recovered plaintext to an [OutputStream].
     *
     * Reads the IV header, initializes the streaming decipher, verifies the authentication tag,
     * and streams plaintext to the destination.
     *
     * @param inputStream Source stream containing the IV header and ciphertext.
     * @param outputStream Destination stream where plaintext will be written.
     * @throws CryptoException.DecryptionException If an I/O error, invalid header, or tag failure occurs.
     */
    override fun decrypt(inputStream: InputStream, outputStream: OutputStream) {
        try {
            val ivSize = inputStream.read()
            if (ivSize <= 0) {
                throw CryptoException.DecryptionException("Corrupted stream: missing or invalid IV size byte.")
            }

            val iv = ByteArray(ivSize)
            val bytesRead = inputStream.read(iv)
            if (bytesRead != ivSize) {
                throw CryptoException.DecryptionException("Corrupted stream: could not read complete IV bytes.")
            }

            val cipher = Cipher.getInstance(TRANSFORMATION)
            val spec = GCMParameterSpec(TAG_LENGTH_BITS, iv)
            cipher.init(Cipher.DECRYPT_MODE, getOrCreateSecretKey(), spec)

            CipherInputStream(inputStream, cipher).use { cipherIn ->
                val buffer = ByteArray(BUFFER_SIZE)
                var readCount: Int
                while (cipherIn.read(buffer).also { readCount = it } != -1) {
                    outputStream.write(buffer, 0, readCount)
                }
                outputStream.flush()
            }
        } catch (e: CryptoException) {
            throw e
        } catch (e: Exception) {
            throw CryptoException.DecryptionException("Streaming decryption failed: ${e.message}", e)
        }
    }

    companion object {
        const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val KEY_SIZE_BITS = 256
        private const val TAG_LENGTH_BITS = 128
        private const val BUFFER_SIZE = 8192
    }
}