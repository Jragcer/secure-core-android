package com.github.jragcer.securitycore.api.crypto

import java.io.InputStream
import java.io.OutputStream

/**
 * High-level cryptographic contract backed by hardware security (AndroidKeyStore)
 * using authenticated AES-256-GCM encryption.
 */
interface CryptoManager {
    /**
     * Encrypts an arbitrary byte array.
     *
     * The resulting payload is framed as follows:
     * - Byte 0: IV length in bytes (N)
     * - Bytes 1..N: Initialization Vector (IV)
     * - Bytes (N+1)..End: Ciphertext appended with the 128-bit GCM authentication tag
     *
     * @param data The plaintext bytes to encrypt.
     * @return Packed byte array containing IV metadata, IV, and authenticated ciphertext.
     * @throws CryptoException.EncryptionException If cipher initialization or encryption fails.
     * @throws CryptoException.KeyStoreAccessException If the underlying hardware key cannot be accessed.
     */
    fun encrypt(data: ByteArray): ByteArray

    /**
     * Decrypts an encrypted payload generated by [encrypt].
     *
     * Automatically unpacks the IV header, verifies the 128-bit GCM authentication tag,
     * and recovers the original plaintext.
     *
     * @param encryptedData The packaged byte array containing IV metadata, IV, and ciphertext.
     * @return The original decrypted plaintext bytes.
     * @throws CryptoException.DecryptionException If the payload is malformed or the auth tag validation fails.
     * @throws CryptoException.KeyStoreAccessException If the underlying hardware key cannot be accessed.
     */
    fun decrypt(encryptedData: ByteArray): ByteArray

    /**
     * Encrypts data from an [InputStream] and writes it into an [OutputStream].
     *
     * Streams data sequentially in chunks, preventing high memory pressure and OutOfMemory errors
     * when processing large payloads or files. Writes the IV header prior to the cipher stream.
     *
     * @param inputStream Source stream carrying plaintext data.
     * @param outputStream Destination stream where the IV header and ciphertext will be written.
     * @throws CryptoException.EncryptionException If an I/O error or encryption error occurs.
     */
    fun encrypt(inputStream: InputStream, outputStream: OutputStream)

    /**
     * Decrypts data from an [InputStream] and writes the recovered plaintext to an [OutputStream].
     *
     * Reads the IV header, initializes the streaming decipher, verifies the authentication tag,
     * and streams plaintext to the destination.
     *
     * @param inputStream Source stream containing the IV header and ciphertext.
     * @param outputStream Destination stream where plaintext will be written.
     * @throws CryptoException.DecryptionException If an I/O error, invalid header, or tag failure occurs.
     */
    fun decrypt(inputStream: InputStream, outputStream: OutputStream)
}